import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
assert.ok(process.argv[2], 'Usage: node scripts/import-krillion-data.mjs <path-to-merged-data.json>');
const sourcePath = path.resolve(process.argv[2]);
const outputPath = path.join(projectRoot, 'krillion', 'data.js');
const source = JSON.parse((await readFile(sourcePath, 'utf8')).replace(/^\uFEFF/, ''));
assert.ok(Array.isArray(source.answers), 'Source must contain an answers array.');

function text(value, label, { allowEmpty = false } = {}) {
  assert.equal(typeof value, 'string', `${label} must be a string; no object coercion is allowed.`);
  assert.ok(allowEmpty || value.trim(), `${label} cannot be empty.`);
  assert.ok(!value.includes('[object Object]'), `${label} contains an invalid coerced object.`);
  assert.ok(!/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i.test(value), `${label} contains an email address.`);
  return value;
}

const supportedModes = new Set(['Daily', 'Endless', 'Movies', 'Sports', 'Geography', 'Lexicon']);
const rows = source.answers.filter(row => row.score === 100 && row.tier === 'krillion');
assert.equal(rows.length, 1085, 'Expected exactly 1,085 listed 100-point Krillion rows.');
const ids = new Set();
const QUESTIONS = rows.map(row => {
  assert.ok(supportedModes.has(row.mode), `Unsupported mode: ${row.mode}`);
  assert.ok(Number.isSafeInteger(row.dive) && row.dive > 0, 'Dive must be a positive integer.');
  assert.ok(Number.isSafeInteger(row.roundNumber) && row.roundNumber >= 1 && row.roundNumber <= 7,
    'Round must be an integer from 1 through 7.');
  const id = `${row.mode}:${row.dive}:${row.roundNumber}`;
  assert.ok(!ids.has(id), `Duplicate question key: ${id}`);
  ids.add(id);
  assert.ok(Array.isArray(row.topAlternatives), `${id}: topAlternatives must be an array.`);
  const answers = [row.answer, ...row.topAlternatives].map((value, index) => text(value, `${id}: answer ${index + 1}`));
  assert.equal(answers.length, row.topTieCount, `${id}: every listed top-score tie must be preserved.`);
  assert.equal(answers.length, row.includedTopCount, `${id}: source tie count does not match included names.`);
  assert.equal(row.topListComplete, true, `${id}: truncated top-answer list is not allowed.`);
  const sourceType = text(row.sourceType, `${id}: sourceType`);
  assert.ok(sourceType.startsWith('Official ') || sourceType === 'Public fan archive', `${id}: unknown provenance.`);
  const sourceUrl = text(row.sourceUrl, `${id}: sourceUrl`);
  assert.equal(new URL(sourceUrl).protocol, 'https:', `${id}: source URL must use HTTPS.`);
  const sourceDate = text(row.sourceDate ?? '', `${id}: sourceDate`, { allowEmpty: true });
  assert.ok(sourceDate === '' || /^\d{4}-\d{2}-\d{2}$/.test(sourceDate), `${id}: invalid source date.`);
  return {
    id, mode: row.mode, dive: row.dive, round: row.roundNumber,
    question: text(row.question, `${id}: question`), answer: answers[0], answers,
    sourceDate, sourceType, sourceUrl
  };
});

const answerCount = QUESTIONS.reduce((count, question) => count + question.answers.length, 0);
assert.equal(answerCount, 1475, 'Expected exactly 1,475 listed top-answer names including ties.');
const officialCount = QUESTIONS.filter(question => question.sourceType.startsWith('Official ')).length;
const communityCount = QUESTIONS.length - officialCount;
assert.equal(officialCount, 249, 'Unexpected official question count.');
assert.equal(communityCount, 836, 'Unexpected community-transcribed question count.');
const META = {
  asOf: '2026-11-16', count: QUESTIONS.length, answerCount, officialCount, communityCount,
  coverageNote: 'Only listed 100-point Krillion answers from the collected dataset are included. Historical daily answers rely on independent fan transcriptions; this is not every game question. All listed top-score ties are preserved. Blank source dates mean no calendar date was published.'
};
const output = `// Generated by scripts/import-krillion-data.mjs. Factual 100-point entries only; see docs/krillion-data.md.\nexport const META = ${JSON.stringify(META, null, 2)};\nexport const QUESTIONS = ${JSON.stringify(QUESTIONS, null, 2)};\n`;
assert.ok(!output.includes('[object Object]'), 'Generated data contains a coerced object.');
assert.ok(!/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i.test(output), 'Generated data contains an email address.');
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, 'utf8');
console.log(JSON.stringify({ count: QUESTIONS.length, answerCount, officialCount, communityCount,
  uniqueIds: ids.size, output: outputPath }));

